#!/bin/bash

# TDD 리마인더 Hook
# .ts, .tsx 파일 Edit/Write 전에 TDD 규칙을 상기시킵니다.

# 환경 변수 확인
FILE_PATH="${FILE_PATH:-}"
TOOL_NAME="${TOOL_NAME:-}"

# .ts 또는 .tsx 파일인지 확인
if [[ "$FILE_PATH" =~ \.(ts|tsx)$ ]]; then
  # 메시지 출력 (stderr로 출력)
  cat >&2 << 'EOF'

╔═══════════════════════════════════════════════════════════════╗
║             🔍 TDD 규칙 확인 필터                             ║
╚═══════════════════════════════════════════════════════════════╝

이 파일을 수정하기 전에 다음을 다시 한 번 확인하세요:

🎯 TDD 적용 대상인가?
   ✓ 비즈니스 로직, API 핸들러, 유틸 함수
   ✓ 버그 수정, 상태 관리 로직, 데이터 변환
   ✗ 타입 정의, 설정 파일, 순수 UI 레이아웃

📋 RED-GREEN-REFACTOR 순서인가?
   1️⃣  RED: 테스트를 먼저 작성 (실패하는 상태)
        → bun test 실행 후 빨간색 확인
   2️⃣  GREEN: 최소한의 코드로 통과
        → bun test 모두 초록색 확인
   3️⃣  REFACTOR: 중복 제거, 이름 개선
        → bun test 여전히 초록색 확인

⚠️  기존 프로덕션 코드가 먼저 작성되었는가?
   → TDD 규칙 위반! 기존 코드를 삭제하고 RED부터 재시작하세요.

📚 자세한 규칙: .claude/rules/tdd.md 참고

╔═══════════════════════════════════════════════════════════════╗

EOF
fi

# 항상 exit 0 (도구 실행 진행)
exit 0
